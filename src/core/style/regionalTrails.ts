import type { LayerSpecification, SourceSpecification } from 'maplibre-gl';
import regionalTrailLabelsRaw from './regionalTrailLabels.json';

/**
 * Named long-distance trails (Golan Trail, Sea to Sea, Makhtesh Ramon circuit, ...) drawn by the
 * `trail-regional-*` layers behind the "regionalTrails" layer switch. Shvil Israel is not part of
 * this set: it keeps its own always-on highlight under the hiking-trails switch.
 *
 * The vector tiles carry each trail's `osmc_symbol` but no route name, and several trails share a
 * symbol, so the name labels are placed along bundled route lines generated by
 * devops/script_helpers/build-regional-trail-labels.mjs.
 */
export interface RegionalTrailLabelRecord {
  osmId: number;
  name: string;
  nameEn: string;
  symbol: string;
  lines: number[][][];
}

export const REGIONAL_TRAILS: readonly RegionalTrailLabelRecord[] =
  regionalTrailLabelsRaw as RegionalTrailLabelRecord[];

export const REGIONAL_TRAILS_SOURCE_ID = 'israel-regional-trails';
export const REGIONAL_TRAIL_NAME_LAYER_ID = 'trail-regional-name';

/** Name-label colour per trail symbol, tuned to read against the day / dark map backgrounds. */
const LABEL_COLOR_BY_SYMBOL: Record<string, { day: string; dark: string }> = {
  'purple:white:purple_stripe': { day: '#800080', dark: '#E6A5F0' },
  'orange:white:orange_stripe': { day: '#C2570A', dark: '#FDBA74' },
  'blue:blue:white_right:purple_stripe': { day: '#1765AD', dark: '#7CB8F2' },
  'green:green:white_right:blue_stripe': { day: '#0B7A0B', dark: '#5EE05E' },
  'yellow:blue:yellow_stripe': { day: '#946200', dark: '#FACC15' },
  'yellow:green:yellow_stripe': { day: '#15803D', dark: '#4ADE80' },
  'green:red:green_left': { day: '#006400', dark: '#86EFAC' },
};

export function buildRegionalTrailsSource(): SourceSpecification {
  return {
    type: 'geojson',
    // The lines only anchor name labels: smoothing ~3 px of wiggle per zoom lets a name fit along
    // winding trails that `text-max-angle` would otherwise reject.
    tolerance: 3,
    data: {
      type: 'FeatureCollection',
      features: REGIONAL_TRAILS.map((trail) => ({
        type: 'Feature' as const,
        properties: { name: trail.name, nameEn: trail.nameEn, symbol: trail.symbol },
        geometry: { type: 'MultiLineString' as const, coordinates: trail.lines },
      })),
    },
  };
}

/**
 * MapLibre places symbols top layer first, so overlay symbol layers added at runtime (the POI
 * tiers) would otherwise crowd the trail names out wherever POIs are dense. Call after adding
 * such layers; it is a no-op once the names already sit above them.
 */
export function raiseRegionalTrailNamesAbove(
  map: {
    getLayer(id: string): unknown;
    getLayersOrder(): string[];
    moveLayer(id: string, beforeId?: string): unknown;
  },
  layerIds: readonly string[]
): void {
  if (!map.getLayer(REGIONAL_TRAIL_NAME_LAYER_ID)) return;
  const order = map.getLayersOrder();
  const nameIdx = order.indexOf(REGIONAL_TRAIL_NAME_LAYER_ID);
  if (layerIds.some((id) => order.indexOf(id) > nameIdx)) {
    map.moveLayer(REGIONAL_TRAIL_NAME_LAYER_ID);
  }
}

export function buildRegionalTrailNameLayer(isDark: boolean, visible: boolean): LayerSpecification {
  const fallbackColor = isDark ? '#CBD5E1' : '#404040';
  const colorMatch: any[] = ['match', ['get', 'symbol']];
  for (const [symbol, colors] of Object.entries(LABEL_COLOR_BY_SYMBOL)) {
    colorMatch.push(symbol, isDark ? colors.dark : colors.day);
  }
  colorMatch.push(fallbackColor);

  return {
    id: REGIONAL_TRAIL_NAME_LAYER_ID,
    type: 'symbol',
    source: REGIONAL_TRAILS_SOURCE_ID,
    // Same floor as the trail-regional-* lines the names belong to.
    minzoom: 11,
    layout: {
      visibility: visible ? 'visible' : 'none',
      'symbol-placement': 'line',
      'symbol-spacing': 400,
      'text-field': ['get', 'name'],
      'text-font': ['bold', 'Arial', 'Tahoma', 'sans-serif'],
      'text-size': ['interpolate', ['linear'], ['zoom'], 11, 10.5, 14, 12, 17, 13.5],
      // Lifts the name clear of the path and its offset colour line instead of sitting on top of them.
      'text-offset': [0, -1.2],
      // Trails wind far more than roads; the default 45° leaves whole map views without a name.
      'text-max-angle': 75,
      'text-padding': 2,
    },
    paint: {
      'text-color': colorMatch as any,
      'text-halo-color': isDark ? '#0B1015' : '#FFFFFF',
      'text-halo-width': 2.2,
      'text-halo-blur': 0.6,
    },
  };
}
