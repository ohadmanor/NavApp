import fs from 'node:fs';
import path from 'node:path';
import { WORKSPACE_DIR, ensureWorkspace } from '../paths.js';
import type { EnrichmentRecord, LogLevel, ResolvedEnrichmentBundle } from '../types.js';

type Logger = (level: LogLevel, message: string) => void;

function escapeLuaString(value: string): string {
  return value
    .replace(/\\/g, '\\\\')
    .replace(/"/g, '\\"')
    .replace(/\r?\n/g, ' ')
    .slice(0, 400);
}

export function extractHazardFromDescription(description?: string): string | undefined {
  if (!description) return undefined;
  const parts: string[] = [];
  if (description.includes('שטפונות:')) parts.push('flash_flood');
  if (description.includes('גשם:')) parts.push('rain_closure');
  if (description.includes('שטח אש:')) parts.push('firing_zone');
  if (description.includes('עומס חום')) parts.push('heatwave');
  return parts.length > 0 ? parts.join(';') : undefined;
}

export function extractActivitiesFromDescription(description?: string): string | undefined {
  if (!description) return undefined;
  const m = /פעילות:\s*([^|]+)/.exec(description);
  if (!m?.[1]) return undefined;
  const raw = m[1];
  const tags: string[] = [];
  if (raw.includes('הליכה')) tags.push('foot');
  if (raw.includes('אופניים')) tags.push('bicycle');
  if (raw.includes("ג'יפים") || raw.includes('נסיעה')) tags.push('4wd');
  if (raw.includes('סוסים')) tags.push('horse');
  return tags.length > 0 ? tags.join(',') : undefined;
}

function serializeLuaEntry(rec: EnrichmentRecord): string {
  const fields: string[] = [];
  if (rec.numbers[0]) fields.push(`ref = "${escapeLuaString(rec.numbers[0])}"`);
  if (rec.colour) fields.push(`colour = "${escapeLuaString(rec.colour)}"`);
  if (rec.osmcSymbol) fields.push(`osmc_symbol = "${escapeLuaString(rec.osmcSymbol)}"`);
  if (rec.description) fields.push(`description = "${escapeLuaString(rec.description)}"`);
  const hazard = rec.hazard || extractHazardFromDescription(rec.description);
  if (hazard) fields.push(`hazard = "${escapeLuaString(hazard)}"`);
  const activities = rec.activities || extractActivitiesFromDescription(rec.description);
  if (activities) fields.push(`activities = "${escapeLuaString(activities)}"`);
  return `{ ${fields.join(', ')} }`;
}

export function generateLuaEnrichmentLookup(
  bundle: ResolvedEnrichmentBundle,
  log: Logger
): { luaPath: string; wayCount: number; refCount: number } {
  ensureWorkspace();
  const lines: string[] = [
    '-- Auto-generated by NavApp PBF-to-PMTiles enrichment injector',
    'return {',
    '  ways = {',
  ];

  const wayEntries = Object.entries(bundle.byWayId);
  for (const [wayId, rec] of wayEntries) {
    lines.push(`    ["${escapeLuaString(wayId)}"] = ${serializeLuaEntry(rec)},`);
  }

  lines.push('  },');
  lines.push('  refs = {');

  const refEntries = Object.entries(bundle.byRef);
  for (const [ref, rec] of refEntries) {
    lines.push(`    ["${escapeLuaString(ref)}"] = ${serializeLuaEntry(rec)},`);
  }

  lines.push('  },');
  lines.push('}');

  const luaPath = path.join(WORKSPACE_DIR, 'enrichment_lookup.lua');
  fs.writeFileSync(luaPath, lines.join('\n'), 'utf8');
  log('info', `Generated Tilemaker enrichment lookup (${wayEntries.length} way overrides, ${refEntries.length} SPNI ref enrichments).`);
  return { luaPath, wayCount: wayEntries.length, refCount: refEntries.length };
}
